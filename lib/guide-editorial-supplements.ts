function classifyGuide(guide: Pick<PolicyGuide, "slug" | "title">): keyof typeof CATEGORY_SOURCE_CHECKS {
  const text = `${guide.slug} ${guide.title}`;
  if (/주거|월세|전세|housing|rent|lease|newlywed/.test(text)) return "housing";
  if (/소상공인|자영업|사업|policy-fund|business|tax-delinquency|self-employed/.test(text)) return "business";
  if (/부모|아이|육아|출산|한부모|장애|노인|family|child|senior|parents|disabled/.test(text)) return "family";
  if (/의료|긴급복지|medical|emergency/.test(text)) return "medical";
  return "default";
}

function topicNoun(title: string): string {
  return title.replace(/ —.*$/, "").replace(/ 신청.*$/, "").replace(/ 확인.*$/, "").trim();
}

