// 알려진 실패의 수정 방향만 안내합니다. 원문 대조와 공개 기준은 완화하지 않습니다.
export function newsRetryGuidance(reason: string) {
  if (reason.includes('작성·개발 작업 지시'))
    return '작성자·개발자에게 지시하는 문장을 독자용 사실 설명으로 다시 쓰세요. 문장을 단순 삭제해 원문의 핵심 조건이나 내용을 누락하지 마세요. 다시 작성한 글 전체에 같은 사실·충실도 검사를 적용합니다.';
  if (reason.includes('원문에서 확인하지 못한 숫자') || reason.includes('숫자와 단위'))
    return '공식 발표일의 월을 원문의 일자에 덧붙이지 마세요. 날짜·숫자·단위는 해당 사실을 설명하는 원문 표현 그대로 보존하고, 맥락으로 추정해야 하는 월이나 연도는 추가하지 마세요.';
  return '';
}
